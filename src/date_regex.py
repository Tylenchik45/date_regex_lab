"""
Функции для проверки и поиска дат в формате ДД.ММ.ГГГГ.
Важной задачей было определить високосные года, а конкретно 29 февраля в таком году.
Соответственно из интернета взято определение:
'Високосным считается год, который делится на 4, но не делится на 100, либо делится на 400.'

Выражение разбито на блоки:
Блок для месяцев с 31 днем.
Блок для месяцев с 30 днями.
Блок для 28 дней в феврале.
Блок для 29 февраля в високосном году.
  Год делится на 4, но не на 100.
  Год делится на 400.

Подробное описание регулярного выражения в README.txt
"""

import re
from typing import List

BIG_MONTH = r"(?:0[1-9]|[12][0-9]|3[01])\.(?:0[13578]|1[02])\.[0-9]{4}|"
SMALL_MONTH = r"(?:0[1-9]|[12][0-9]|30)\.(?:0[469]|11)\.[0-9]{4}|"
NON_LEAP_FEBRUARY = r"(?:0[1-9]|1[0-9]|2[0-8])\.02\.[0-9]{4}|"
LEAP_FEBRUARY = r"29\.02\.(?:[0-9]{2}(?:0[48]|[2468][048]|[13579][26])|(?:[02468][048]|[13579][26])00)"
DATE_CORE = r"(?:" + BIG_MONTH + SMALL_MONTH + NON_LEAP_FEBRUARY + LEAP_FEBRUARY + r")"
DATE_VALIDATION_REG = re.compile(DATE_CORE)

# (?<!\d) - перед датой не должно быть цифры
# (?<!\.) - перед датой не должно быть точки
# (?!\d) - после даты не должно быть цифры
# (?!\.\d) - после даты не должно быть точки, за которой идёт цифра
DATE_SEARCH_PATTERN = re.compile(r"(?<!\d)(?<!\.)" + DATE_CORE + r"(?!\d)(?!\.\d)")


def is_valid_date(value: object) -> bool:
    """Проверяет, является ли значение корректной датой ДД.ММ.ГГГГ.

    Функция принимает на вход value. Проверяем то, что это строка.

    Функция возвращает True, если значение является строкой и полностью совпадает
    с корректной датой. Иначе False.
    """
    if not isinstance(value, str):
        return False

    return DATE_VALIDATION_REG.fullmatch(value) is not None


def find_dates(text: str) -> List[str]:
    """Ищет все корректные даты ДД.ММ.ГГГГ в произвольном тексте.

    Функция принимает на вход text: Текст, в котором выполняется поиск.

    Функция возвращает Список найденных дат в порядке их появления в тексте.

    Возможная ошибка TypeError: Если text не является строкой.
    """
    if not isinstance(text, str):
        raise TypeError("Входное значение должно быть строковым текстом")

    return [match.group(0) for match in DATE_SEARCH_PATTERN.finditer(text)]
